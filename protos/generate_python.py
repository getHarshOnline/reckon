"""Generate Python wire bindings using the Python plugin in buf.gen.yaml."""

import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys
import sysconfig
from tempfile import TemporaryDirectory

import yaml


def generate(output: Path) -> None:
    """Compile every schema together; preserve the configured package layout."""
    root = Path(__file__).resolve().parent
    config = yaml.safe_load((root / "buf.gen.yaml").read_text())
    plugin = next(
        item for item in config["plugins"] if item["local"] == "protoc-gen-python_betterproto2"
    )
    executable = shutil.which(
        plugin["local"],
        path=sysconfig.get_path("scripts") + os.pathsep + os.environ.get("PATH", ""),
    )
    if executable is None:
        raise SystemExit("Install the proto extra in this Python 3.10+ environment first.")
    output.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            sys.executable,
            "-m",
            "grpc_tools.protoc",
            f"-I{root}",
            f"--plugin={plugin['local']}={executable}",
            f"--python_betterproto2_out={output}",
            f"--python_betterproto2_opt={','.join(plugin['opt'])}",
            *map(str, sorted((root / "reckon").rglob("*.proto"))),
        ],
        check=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Compare generated bytes without changing source."
    )
    args = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / "src/reckon/generated"
    with TemporaryDirectory(prefix="reckon-proto-") as temporary:
        generated = Path(temporary)
        generate(generated)
        outputs = {
            path.relative_to(generated): path.read_bytes() for path in generated.rglob("*.py")
        }
        existing = {
            path.relative_to(destination): path.read_bytes() for path in destination.rglob("*.py")
        }
        if args.check:
            if existing != outputs:
                raise SystemExit("Python bindings differ: run python protos/generate_python.py.")
            print("Python wire bindings match all protocol sources and configured options.")
        else:
            if unexpected := existing.keys() - outputs.keys():
                raise SystemExit(
                    f"Review obsolete generated files before replacement: {sorted(map(str, unexpected))}; no files changed."
                )
            for relative, content in outputs.items():
                target = destination / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)


if __name__ == "__main__":
    main()
