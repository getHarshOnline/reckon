"""
Statistical Tests for Causal Probing.

Pure Python implementations that work without scipy.
scipy is optional for t-test convenience.

Key Functions:
    - permutation_test: Non-parametric two-sample test (pure Python)
    - t_test: Parametric two-sample test (requires scipy)
    - cohens_d: Effect size calculation
    - confidence_interval: Bootstrap or normal approximation CI
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass
from typing import List, Tuple, Optional, cast

__all__ = [
    "PermutationTestResult",
    "TTestResult",
    "permutation_test",
    "t_test",
    "cohens_d",
    "confidence_interval",
    "pooled_std",
]


@dataclass
class PermutationTestResult:
    """Result of a permutation test."""

    statistic: float  # Observed difference in means
    p_value: float  # Two-sided p-value
    n_permutations: int  # Number of permutations used
    observed_diff: float  # Same as statistic
    null_distribution_mean: float
    null_distribution_std: float


@dataclass
class TTestResult:
    """Result of a t-test."""

    statistic: float  # t-statistic
    p_value: float  # Two-sided p-value
    df: float  # Degrees of freedom


def _mean(values: List[float]) -> float:
    """Calculate mean of a list."""
    if not values:
        return 0.0
    return sum(values) / len(values)


def _variance(values: List[float], ddof: int = 1) -> float:
    """Calculate sample variance."""
    if len(values) <= ddof:
        return 0.0
    m = _mean(values)
    return sum((x - m) ** 2 for x in values) / (len(values) - ddof)


def _std(values: List[float], ddof: int = 1) -> float:
    """Calculate sample standard deviation."""
    return math.sqrt(_variance(values, ddof))


def pooled_std(x: List[float], y: List[float]) -> float:
    """
    Calculate pooled standard deviation for two samples.

    Formula: sqrt(((n1-1)*s1^2 + (n2-1)*s2^2) / (n1+n2-2))

    Args:
        x: First sample
        y: Second sample

    Returns:
        Pooled standard deviation
    """
    n1, n2 = len(x), len(y)
    if n1 + n2 <= 2:
        return 0.0

    var1 = _variance(x, ddof=1)
    var2 = _variance(y, ddof=1)

    pooled_var = ((n1 - 1) * var1 + (n2 - 1) * var2) / (n1 + n2 - 2)
    return math.sqrt(pooled_var)


def cohens_d(x: List[float], y: List[float]) -> float:
    """
    Calculate Cohen's d effect size.

    Cohen's d = (mean(x) - mean(y)) / pooled_std

    Interpretation:
        - |d| < 0.2: negligible
        - 0.2 <= |d| < 0.5: small
        - 0.5 <= |d| < 0.8: medium
        - |d| >= 0.8: large

    Args:
        x: First sample (e.g., baseline)
        y: Second sample (e.g., intervention)

    Returns:
        Cohen's d effect size
    """
    if not x or not y:
        return 0.0

    mean_diff = _mean(x) - _mean(y)
    s_pooled = pooled_std(x, y)

    if s_pooled == 0:
        return 0.0 if mean_diff == 0 else float("inf") * (1 if mean_diff > 0 else -1)

    return mean_diff / s_pooled


def permutation_test(
    x: List[float],
    y: List[float],
    n_permutations: int = 10000,
    seed: Optional[int] = None,
) -> PermutationTestResult:
    """
    Two-sample permutation test (pure Python, no scipy).

    Tests whether two samples come from the same distribution
    by comparing the observed difference in means to a null
    distribution generated by randomly permuting labels.

    Args:
        x: First sample (e.g., baseline outcomes)
        y: Second sample (e.g., intervention outcomes)
        n_permutations: Number of random permutations
        seed: Random seed for reproducibility

    Returns:
        PermutationTestResult with p-value and statistics

    Example:
        >>> baseline = [0.5, 0.6, 0.55, 0.58, 0.52]
        >>> intervention = [0.7, 0.75, 0.68, 0.72, 0.71]
        >>> result = permutation_test(baseline, intervention)
        >>> print(f"p-value: {result.p_value:.4f}")
    """
    if not x or not y:
        return PermutationTestResult(
            statistic=0.0,
            p_value=1.0,
            n_permutations=0,
            observed_diff=0.0,
            null_distribution_mean=0.0,
            null_distribution_std=0.0,
        )

    # Set random seed if provided
    if seed is not None:
        random.seed(seed)

    # Observed difference in means
    observed_diff = _mean(x) - _mean(y)

    # Combine samples
    combined = list(x) + list(y)
    n_x = len(x)

    # Generate null distribution by permuting labels
    null_diffs: List[float] = []

    for _ in range(n_permutations):
        # Shuffle combined data
        random.shuffle(combined)

        # Split into two groups
        perm_x = combined[:n_x]
        perm_y = combined[n_x:]

        # Calculate difference
        perm_diff = _mean(perm_x) - _mean(perm_y)
        null_diffs.append(perm_diff)

    # Calculate two-sided p-value
    # p = proportion of permutations with |diff| >= |observed|
    n_extreme = sum(1 for d in null_diffs if abs(d) >= abs(observed_diff))
    p_value = (n_extreme + 1) / (n_permutations + 1)  # +1 to include observed

    return PermutationTestResult(
        statistic=observed_diff,
        p_value=p_value,
        n_permutations=n_permutations,
        observed_diff=observed_diff,
        null_distribution_mean=_mean(null_diffs),
        null_distribution_std=_std(null_diffs) if len(null_diffs) > 1 else 0.0,
    )


def t_test(x: List[float], y: List[float]) -> TTestResult:
    """
    Independent two-sample t-test.

    Requires scipy. If scipy is not available, raises ImportError
    with a suggestion to use permutation_test instead.

    Args:
        x: First sample
        y: Second sample

    Returns:
        TTestResult with t-statistic, p-value, and degrees of freedom

    Raises:
        ImportError: If scipy is not installed
    """
    try:
        # Other tests remain usable without loading SciPy.
        # pylint: disable-next=import-outside-toplevel
        from scipy import stats
    except ImportError as error:
        raise ImportError(
            "scipy is required for t_test. "
            "Install with 'pip install scipy' or use permutation_test instead."
        ) from error

    if not x or not y:
        return TTestResult(statistic=0.0, p_value=1.0, df=0.0)

    result = stats.ttest_ind(x, y)

    # Calculate degrees of freedom (Welch's approximation not used here)
    df = len(x) + len(y) - 2

    # scipy returns named tuple with statistic and pvalue attributes
    # Use getattr for type safety with older scipy versions
    stat: float = cast(float, getattr(result, "statistic", result[0]))
    pval: float = cast(float, getattr(result, "pvalue", result[1]))

    return TTestResult(
        statistic=stat,
        p_value=pval,
        df=float(df),
    )


def confidence_interval(
    x: List[float],
    confidence: float = 0.95,
    method: str = "normal",
    n_bootstrap: int = 1000,
    seed: Optional[int] = None,
) -> Tuple[float, float]:
    """
    Calculate confidence interval for the mean.

    Args:
        x: Sample data
        confidence: Confidence level (e.g., 0.95 for 95% CI)
        method: "normal" (assumes normality) or "bootstrap" (non-parametric)
        n_bootstrap: Number of bootstrap samples (for bootstrap method)
        seed: Random seed for reproducibility

    Returns:
        Tuple of (lower_bound, upper_bound)
    """
    if not x:
        return (0.0, 0.0)

    if len(x) == 1:
        return (x[0], x[0])

    if method == "normal":
        # Normal approximation using z-score
        # For 95% CI, z ≈ 1.96
        # Pure Python approximation of z-score for common confidence levels
        z_scores = {
            0.90: 1.645,
            0.95: 1.96,
            0.99: 2.576,
        }
        z = z_scores.get(confidence, 1.96)

        margin = z * (_std(x) / math.sqrt(len(x)))
        return (_mean(x) - margin, _mean(x) + margin)

    if method == "bootstrap":
        if seed is not None:
            random.seed(seed)

        # Bootstrap: resample with replacement and compute means
        bootstrap_means: List[float] = []
        for _ in range(n_bootstrap):
            resample = [random.choice(x) for _ in range(len(x))]
            bootstrap_means.append(_mean(resample))

        # Sort and find percentiles
        bootstrap_means.sort()
        alpha = 1 - confidence
        lower_idx = int((alpha / 2) * n_bootstrap)
        upper_idx = int((1 - alpha / 2) * n_bootstrap) - 1

        lower_idx = max(0, min(lower_idx, n_bootstrap - 1))
        upper_idx = max(0, min(upper_idx, n_bootstrap - 1))

        return (bootstrap_means[lower_idx], bootstrap_means[upper_idx])

    raise ValueError(f"Unknown method: {method}. Use 'normal' or 'bootstrap'.")
